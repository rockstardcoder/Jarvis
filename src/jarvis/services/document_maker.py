import os
import re
from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.section import WD_SECTION
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor


DOCUMENT_DIR = Path(
    "data/documents"
)


THEMES = {
    "professional": {
        "accent": RGBColor(31, 78, 121),
        "accent_hex": "1F4E79",
        "dark": RGBColor(25, 35, 50),
        "muted": RGBColor(90, 105, 125),
        "light_hex": "EAF2F8"
    },
    "school": {
        "accent": RGBColor(40, 90, 180),
        "accent_hex": "285AB4",
        "dark": RGBColor(30, 45, 75),
        "muted": RGBColor(85, 100, 130),
        "light_hex": "EDF3FF"
    },
    "essay": {
        "accent": RGBColor(70, 70, 70),
        "accent_hex": "464646",
        "dark": RGBColor(25, 25, 25),
        "muted": RGBColor(90, 90, 90),
        "light_hex": "F2F2F2"
    },
    "notes": {
        "accent": RGBColor(0, 135, 105),
        "accent_hex": "008769",
        "dark": RGBColor(20, 55, 50),
        "muted": RGBColor(80, 110, 105),
        "light_hex": "E8F7F2"
    }
}


class DocumentMaker:

    def ensure_output_folder(
        self
    ):
        DOCUMENT_DIR.mkdir(
            parents=True,
            exist_ok=True
        )

    def sanitize_filename(
        self,
        text: str
    ) -> str:
        text = str(text).lower().strip()

        text = re.sub(
            r"[^a-z0-9]+",
            "_",
            text
        )

        text = text.strip("_")

        if not text:
            text = "document"

        return text[:60]

    def clean_topic(
        self,
        topic: str
    ) -> str:
        topic = str(topic).strip()

        if not topic:
            return "Untitled Document"

        return topic[0].upper() + topic[1:]

    def create_output_path(
        self,
        topic: str,
        doc_type: str
    ) -> Path:
        self.ensure_output_folder()

        timestamp = datetime.now().strftime(
            "%Y-%m-%d_%H-%M-%S"
        )

        filename = (
            f"{self.sanitize_filename(topic)}_"
            f"{self.sanitize_filename(doc_type)}_"
            f"{timestamp}.docx"
        )

        return DOCUMENT_DIR / filename

    def set_cell_background(
        self,
        cell,
        fill_hex: str
    ):
        tc_pr = cell._tc.get_or_add_tcPr()

        shading = OxmlElement(
            "w:shd"
        )

        shading.set(
            qn("w:fill"),
            fill_hex
        )

        tc_pr.append(
            shading
        )

    def set_cell_text(
        self,
        cell,
        text: str,
        bold: bool = False,
        color=None
    ):
        cell.text = ""

        paragraph = cell.paragraphs[0]
        run = paragraph.add_run(
            text
        )

        run.font.name = "Aptos"
        run.font.size = Pt(
            10.5
        )
        run.font.bold = bold

        if color is not None:
            run.font.color.rgb = color

    def configure_document(
        self,
        document,
        theme: dict,
        topic: str,
        doc_type: str
    ):
        section = document.sections[0]
        section.top_margin = Inches(
            0.75
        )
        section.bottom_margin = Inches(
            0.75
        )
        section.left_margin = Inches(
            0.8
        )
        section.right_margin = Inches(
            0.8
        )

        normal_style = document.styles["Normal"]
        normal_style.font.name = "Aptos"
        normal_style.font.size = Pt(
            11
        )
        normal_style.font.color.rgb = theme["dark"]

        footer = section.footer
        paragraph = footer.paragraphs[0]
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER

        run = paragraph.add_run(
            f"Generated by Jarvis • {doc_type.title()} • {topic}"
        )
        run.font.name = "Aptos"
        run.font.size = Pt(
            8
        )
        run.font.color.rgb = theme["muted"]

    def add_title_page(
        self,
        document,
        topic: str,
        doc_type: str,
        theme: dict
    ):
        paragraph = document.add_paragraph()
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER

        run = paragraph.add_run(
            "JARVIS DOCUMENT"
        )
        run.font.name = "Aptos"
        run.font.size = Pt(
            12
        )
        run.font.bold = True
        run.font.color.rgb = theme["accent"]

        document.add_paragraph()

        title = document.add_paragraph()
        title.alignment = WD_ALIGN_PARAGRAPH.CENTER

        title_run = title.add_run(
            topic
        )
        title_run.font.name = "Aptos Display"
        title_run.font.size = Pt(
            30
        )
        title_run.font.bold = True
        title_run.font.color.rgb = theme["dark"]

        subtitle = document.add_paragraph()
        subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER

        subtitle_run = subtitle.add_run(
            doc_type.title()
        )
        subtitle_run.font.name = "Aptos"
        subtitle_run.font.size = Pt(
            16
        )
        subtitle_run.font.color.rgb = theme["muted"]

        document.add_paragraph()

        date_text = datetime.now().strftime(
            "%d %B %Y"
        )

        date_para = document.add_paragraph()
        date_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

        date_run = date_para.add_run(
            date_text
        )
        date_run.font.name = "Aptos"
        date_run.font.size = Pt(
            11
        )
        date_run.font.color.rgb = theme["muted"]

        document.add_page_break()

    def add_section_heading(
        self,
        document,
        text: str,
        theme: dict
    ):
        paragraph = document.add_paragraph()
        paragraph.space_before = Pt(
            10
        )
        paragraph.space_after = Pt(
            5
        )

        run = paragraph.add_run(
            text
        )
        run.font.name = "Aptos Display"
        run.font.size = Pt(
            17
        )
        run.font.bold = True
        run.font.color.rgb = theme["accent"]

    def add_body_paragraph(
        self,
        document,
        text: str
    ):
        paragraph = document.add_paragraph()
        paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        paragraph.space_after = Pt(
            7
        )

        run = paragraph.add_run(
            text
        )
        run.font.name = "Aptos"
        run.font.size = Pt(
            11
        )

    def add_bullets(
        self,
        document,
        bullets: list[str]
    ):
        for bullet in bullets:
            paragraph = document.add_paragraph(
                style="List Bullet"
            )
            paragraph.space_after = Pt(
                4
            )

            run = paragraph.add_run(
                bullet
            )
            run.font.name = "Aptos"
            run.font.size = Pt(
                11
            )

    def add_key_points_table(
        self,
        document,
        rows: list[tuple[str, str]],
        theme: dict
    ):
        table = document.add_table(
            rows=1,
            cols=2
        )

        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.style = "Table Grid"

        header_cells = table.rows[0].cells

        self.set_cell_background(
            header_cells[0],
            theme["accent_hex"]
        )

        self.set_cell_background(
            header_cells[1],
            theme["accent_hex"]
        )

        self.set_cell_text(
            header_cells[0],
            "Key Area",
            bold=True,
            color=RGBColor(255, 255, 255)
        )

        self.set_cell_text(
            header_cells[1],
            "Explanation",
            bold=True,
            color=RGBColor(255, 255, 255)
        )

        for key_area, explanation in rows:
            cells = table.add_row().cells

            self.set_cell_background(
                cells[0],
                theme["light_hex"]
            )

            self.set_cell_text(
                cells[0],
                key_area,
                bold=True
            )

            self.set_cell_text(
                cells[1],
                explanation
            )

        document.add_paragraph()

