    def create_document(
        self,
        topic: str,
        doc_type: str = "professional"
    ) -> str:
        topic = self.clean_topic(
            topic
        )

        doc_type = str(
            doc_type
        ).lower().strip()

        if doc_type not in THEMES:
            doc_type = "professional"

        theme = THEMES[doc_type]

        content = self.build_content(
            topic,
            doc_type
        )

        document = Document()

        self.configure_document(
            document,
            theme,
            topic,
            doc_type
        )

        self.add_title_page(
            document,
            topic,
            doc_type,
            theme
        )

        self.add_section_heading(
            document,
            content["intro_title"],
            theme
        )

        for paragraph in content["intro"]:
            self.add_body_paragraph(
                document,
                paragraph
            )

        self.add_section_heading(
            document,
            "Key Points",
            theme
        )

        self.add_key_points_table(
            document,
            content["table"],
            theme
        )

        for title, paragraphs, bullets in content["sections"]:
            self.add_section_heading(
                document,
                title,
                theme
            )

            for paragraph in paragraphs:
                self.add_body_paragraph(
                    document,
                    paragraph
                )

            if bullets:
                self.add_bullets(
                    document,
                    bullets
                )

        self.add_section_heading(
            document,
            "Conclusion",
            theme
        )

        for paragraph in content["conclusion"]:
            self.add_body_paragraph(
                document,
                paragraph
            )

        output_path = self.create_output_path(
            topic,
            doc_type
        )

        document.save(
            output_path
        )

        return f"Document created: {output_path}"

    def open_document_folder(
        self
    ) -> str:
        try:
            self.ensure_output_folder()

            os.startfile(
                str(DOCUMENT_DIR.resolve())
            )

            return "Opening documents folder."

        except Exception as e:
            return f"Failed to open documents folder: {e}"